#!/usr/bin/env python3
"""Generate Prometheus SLO rules from observability/slo/slos.yaml.

Writes charts/observability/files/rules/slo.rules.yaml (plain Prometheus rule
groups, used by both the local compose stack and the Helm chart).

Naming follows Sloth's conventions so the rules read familiarly:
  slo:sli_error:ratio_rate<window>{slo=...}   bad/total over a window
  slo:objective:ratio{slo=...}                 target, e.g. 0.995
  slo:error_budget:ratio{slo=...}              1 - objective
  slo:current_burn_rate:ratio{slo=...}         5m error ratio / budget
  slo:period_error_budget_remaining:ratio      share of the 28d budget left
"""
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = ROOT / "observability/slo/slos.yaml"
OUT = ROOT / "charts/observability/files/rules/slo.rules.yaml"

WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
# (severity, long window, short window, burn-rate factor) — SRE workbook table 5-8.
BURN_ALERTS = [
    ("page", "1h", "5m", 14.4),
    ("page", "6h", "30m", 6),
    ("ticket", "1d", "2h", 3),
    ("ticket", "3d", "6h", 1),
]


def _expr(template: str, window: str) -> str:
    return " ".join(template.replace("{{window}}", window).split())


def build(spec: dict) -> dict:
    period = spec["window"]
    groups = []
    for slo in spec["slos"]:
        name, labels = slo["name"], {"slo": slo["name"], "layer": slo["layer"]}
        budget = round(1 - slo["objective"] / 100, 6)
        sli_rules = [
            {
                "record": f"slo:sli_error:ratio_rate{w}",
                # ">= 0" drops the 0/0 = NaN of a window with no traffic.
                "expr": f"(({_expr(slo['bad'], w)})\n/\n({_expr(slo['total'], w)})) >= 0",
                "labels": labels,
            }
            for w in WINDOWS
        ]
        # One NaN makes avg_over_time NaN for its whole range, which would blank the
        # SLO for 28 days after a quiet moment, so the average skips any.
        sli_rules.append({
            "record": f"slo:sli_error:ratio_rate{period}",
            "expr": f"avg_over_time((slo:sli_error:ratio_rate5m{{slo=\"{name}\"}} >= 0)[{period}:5m])",
            "labels": labels,
        })
        meta_rules = [
            {"record": "slo:objective:ratio", "expr": f"vector({slo['objective'] / 100})", "labels": labels},
            {"record": "slo:error_budget:ratio", "expr": f"vector({budget})", "labels": labels},
            {"record": "slo:current_burn_rate:ratio",
             "expr": f"slo:sli_error:ratio_rate5m{{slo=\"{name}\"}}\n/ on (slo, layer) group_left\n"
                     f"slo:error_budget:ratio{{slo=\"{name}\"}}",
             "labels": labels},
            {"record": "slo:period_error_budget_remaining:ratio",
             "expr": f"1 - slo:sli_error:ratio_rate{period}{{slo=\"{name}\"}}\n/ on (slo, layer) group_left\n"
                     f"slo:error_budget:ratio{{slo=\"{name}\"}}",
             "labels": labels},
        ]
        alerts = []
        for severity, long_w, short_w, factor in BURN_ALERTS:
            alerts.append({
                "alert": f"SLOBurn{''.join(p.title() for p in name.split('-'))}{long_w.title()}",
                "expr": (f"(slo:sli_error:ratio_rate{long_w}{{slo=\"{name}\"}} > ({factor} * {budget}))\n"
                         f"and\n(slo:sli_error:ratio_rate{short_w}{{slo=\"{name}\"}} > ({factor} * {budget}))"),
                "labels": {**labels, "severity": severity, "burn_window": f"{long_w}/{short_w}"},
                "annotations": {
                    "summary": f"{name} is burning its error budget {factor}x too fast ({long_w}/{short_w} windows)",
                    "description": slo["description"].strip(),
                },
            })
        groups += [
            {"name": f"slo-sli-{name}", "interval": "30s", "rules": sli_rules},
            {"name": f"slo-meta-{name}", "interval": "30s", "rules": meta_rules},
            {"name": f"slo-alerts-{name}", "rules": alerts},
        ]

    groups.append({"name": "inference-saturation", "rules": [
        {"alert": a["name"], "expr": a["expr"], "for": a["for"], "labels": {"severity": "warning"},
         "annotations": {"summary": a["summary"]}}
        for a in spec.get("saturation_alerts", [])
    ]})
    return {"groups": groups}


def _literal_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


def main():
    spec = yaml.safe_load(SPEC.read_text())
    yaml.add_representer(str, _literal_presenter)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = "# GENERATED by observability/slo/generate.py from observability/slo/slos.yaml. Do not edit.\n"
    OUT.write_text(header + yaml.dump(build(spec), sort_keys=False, width=120))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
